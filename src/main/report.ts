export async function buildVulnReport(report: VulnReport, outFile: string): Promise<void> {
  const workbook = newWorkbook();
  const ws = workbook.addWorksheet('IP');

  ws.columns = WIDTHS.map((width) => ({ width }));

  // --- title bar (row 2) ------------------------------------------------
  const title = report.title.trim() || 'Vulnerability Assessment';
  for (let col = 2; col <= 10; col += 1) {
    const cell = ws.getCell(2, col);
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
  }
  const titleCell = ws.getCell('B2');
  titleCell.value = title;
  titleCell.font = TITLE_FONT;
  titleCell.alignment = { vertical: 'middle', horizontal: 'left' };
  ws.getRow(2).height = 24.75;

  // --- header row (row 4) ----------------------------------------------
  HEADERS.forEach((label, i) => {
    const cell = ws.getCell(4, i + 1);
    cell.value = label;
    if (i === 0) {
      cell.font = { ...BODY_FONT, bold: true };
      cell.alignment = { vertical: 'top', horizontal: 'left' };
      return;
    }
    cell.font = HEAD_FONT;
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
    cell.alignment = {
      vertical: 'middle',
      horizontal: i === 9 ? 'left' : 'center',
      wrapText: true
    };
    cell.border = border();
  });
  ws.getRow(4).height = 20.25;

  // --- finding rows ------------------------------------------------------
  for (let index = 0; index < report.findings.length; index += 1) {
    const finding = report.findings[index];
    const rowNo = 5 + index;
    const row = ws.getRow(rowNo);

    const num = ws.getCell(rowNo, 1);
    num.value = index + 1;
    num.font = { ...BODY_FONT, bold: true };
    num.alignment = { vertical: 'top', horizontal: 'left' };

    const risk = ws.getCell(rowNo, 2);
    risk.value = finding.cvss
      ? `${finding.risk}\nCVSS ${finding.cvss.score.toFixed(1)}`
      : finding.risk;
    const riskStyle = RISK_STYLE[finding.risk] ?? RISK_STYLE.Info;
    risk.font = { ...BODY_FONT, bold: riskStyle.bold, color: { argb: 'FFFFFFFF' } };
    risk.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: riskStyle.fill } };
    risk.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
    risk.border = border();

    const meta: string[] = [];
    if (finding.cwe) meta.push(`[${finding.cwe}]`);
    if (finding.controls?.length) meta.push(`Controls: ${finding.controls.join(', ')}`);
    const descriptionText = meta.length
      ? `${finding.description}\n${meta.join('  ')}`
      : finding.description;
    const statusText = findingIsOpen(finding)
      ? `${finding.status} · ${findingOpenDays(finding)}d${findingBreached(finding) ? ' ⚠' : ''}`
      : finding.status;

    const values: Array<number | string> = [
      findingHosts(finding).join('\n'),
      descriptionText,
      finding.riskDetail,
      '', // Evidence: filled by the image below, or a fallback note
      finding.solution,
      timelineText(finding.timeline),
      statusText,
      finding.team
    ];
    values.forEach((value, i) => {
      const cell = ws.getCell(rowNo, i + 3);
      cell.value = value || '';
      cell.font = BODY_FONT;
      cell.alignment = bodyAlign();
      cell.border = border();
    });

    let height = 30;
    for (let col = 1; col < HEADERS.length; col += 1) {
      const text = String(ws.getCell(rowNo, col + 1).value ?? '');
      height = Math.max(height, textLines(text, CHARS_PER_LINE[col]) * 16.5 + 8);
    }

    // --- evidence screenshot embedded in column F ------------------------
    let imageHeight = 0;
    if (finding.evidence) {
      try {
        const buffer = await readFile(finding.evidence);
        const dims = imageSize(buffer);
        const type = (dims.type ?? '').toLowerCase();
        const extension: 'png' | 'gif' | 'jpeg' | null =
          type === 'png'
            ? 'png'
            : type === 'gif'
              ? 'gif'
              : type === 'jpg' || type === 'jpeg'
                ? 'jpeg'
                : null;
        if (extension && dims.width && dims.height) {
          const maxWidth = 460;
          const maxHeight = 330;
          const scale = Math.min(1, maxWidth / dims.width, maxHeight / dims.height);
          const width = Math.max(1, Math.round(dims.width * scale));
          imageHeight = Math.max(1, Math.round(dims.height * scale));
          const imageId = workbook.addImage({ buffer: buffer as unknown as ArrayBuffer, extension });
          ws.addImage(imageId, {
            tl: { col: 5.06, row: rowNo - 1 + 0.2 },
            ext: { width, height: imageHeight }
          });
        }
      } catch {
        const evidence = ws.getCell(rowNo, 6);
        evidence.value = `Evidence file missing: ${basename(finding.evidence)}`;
        evidence.font = { ...BODY_FONT, italic: true, color: { argb: 'FF808080' } };
      }
    }

    row.height = Math.min(409, Math.max(height, imageHeight + 12));
  }

  // --- SLA + compliance coverage summary ---------------------------------
  if (report.findings.length) {
    const openCount = report.findings.filter((f) => findingIsOpen(f)).length;
    const breachCount = report.findings.filter((f) => findingBreached(f)).length;
    const controlCounts = new Map<string, number>();
    for (const f of report.findings) {
      for (const c of f.controls ?? []) controlCounts.set(c, (controlCounts.get(c) ?? 0) + 1);
    }
    const controlList = [...controlCounts.entries()]
      .map(([c, n]) => `${c} \u00d7${n}`)
      .join(', ');
    const summaryRowNo = 5 + report.findings.length + 1;
    ws.mergeCells(summaryRowNo, 1, summaryRowNo, 10);
    const summaryCell = ws.getCell(summaryRowNo, 1);
    summaryCell.value = `SLA: ${openCount} open \u00b7 ${breachCount} breached   |   Compliance coverage: ${
      controlList || '\u2014'
    }`;
    summaryCell.font = { ...BODY_FONT, bold: true };
    summaryCell.alignment = { vertical: 'middle', horizontal: 'left', wrapText: true };
    summaryCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: HEADER_FILL } };
    summaryCell.border = border();
    ws.getRow(summaryRowNo).height = 20;
  }

  ws.autoFilter = 'A4:J4';
  polishSheet(ws, 4, 2);
  await workbook.xlsx.writeFile(outFile);
}
