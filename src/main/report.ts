function timelineText(iso?: string): string {
  if (!iso) return '';
  const [y, m, d] = iso.split('-');
  return y && m && d ? `${d}/${m}/${y}` : iso;
}

function textLines(text: string, chars: number): number {
  if (!text || chars <= 0) return 1;
  return text
    .split('\n')
    .reduce((sum, part) => sum + Math.max(1, Math.ceil(part.length / chars)), 0);
}

function bodyAlign(): Partial<Alignment> {
  return { vertical: 'top', horizontal: 'left', wrapText: true };
}

function border(): Partial<Borders> {
  return { top: THIN, left: THIN, bottom: THIN, right: THIN };
}

/** Workbook with consistent authorship metadata. */
export function newWorkbook(): Workbook {
  const wb = new Workbook();
  wb.creator = 'ANZIKA';
  wb.lastModifiedBy = 'ANZIKA';
  wb.created = new Date();
  return wb;
}

/** Shared polish: frozen panes, hidden gridlines, landscape print, footer. */
export function polishSheet(ws: Worksheet, freezeRows: number, freezeCols = 0): void {
  ws.views = [
    {
      state: 'frozen',
      ySplit: freezeRows,
      ...(freezeCols ? { xSplit: freezeCols } : {}),
      showGridLines: false
    }
  ];
  ws.pageSetup = {
    orientation: 'landscape',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    paperSize: 9
  };
  ws.headerFooter = {
    oddFooter: '&LGenerated by ANZIKA&CFor Internal Use Only&RPage &P of &N'
  };
}

/**
 * Persists a pasted/attached screenshot under the app's data folder and
 * returns its absolute path (referenced by findings, embedded on export).
 */
export async function saveEvidenceFile(base64: string, mime: string): Promise<string> {
  const dir = join(app.getPath('userData'), 'evidence');
  await mkdir(dir, { recursive: true });
  const subtype = (mime.split('/')[1] ?? 'png').toLowerCase().replace('jpeg', 'jpg');
  const ext = /^[a-z0-9]{1,8}$/.test(subtype) ? subtype : 'png';
  const file = join(dir, `ev_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}.${ext}`);
  await writeFile(file, Buffer.from(base64, 'base64'));
  return file;
}

