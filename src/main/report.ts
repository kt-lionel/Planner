function ordinal(day: number): string {
  const suffix = ['th', 'st', 'nd', 'rd'];
  const mod100 = day % 100;
  return `${day}${suffix[(mod100 - 20) % 10] ?? suffix[mod100] ?? suffix[0]}`;
}

export function parseIsoDate(iso: string): Date {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, (m ?? 1) - 1, d ?? 1);
}

export function fmtShort(date: Date): string {
  return `${ordinal(date.getDate())} ${MONTHS_SHORT[date.getMonth()]}`;
}

export function fmtLong(date: Date): string {
  return `${ordinal(date.getDate())} ${MONTHS_LONG[date.getMonth()]}`;
}

export function statusLabel(task: Task): string {
  if (task.status === 'done') return '100% Completed';
  if (task.status === 'in_progress') return 'In Progress';
  if (task.status === 'blocked') return 'Blocked';
  if (task.status === 'canceled') return 'Canceled';
  return 'To do';
}

interface ReportLine {
  value?: CellValue;
  plain?: string;
  indent?: number;
  bold?: boolean;
  color?: string;
  spacer?: boolean;
}

function taskItem(task: Task): ReportLine {
  const date = fmtLong(parseIsoDate(task.date));
  const due =
    task.recurrence === 'none' && task.dueDate
      ? ` \u00b7 due ${fmtLong(parseIsoDate(task.dueDate))}`
      : '';
  const runs: RichText[] = [
    { text: `\u25e6 ${task.title}${task.notes ? ': ' : ' '}`, font: { bold: true } }
  ];
  if (task.notes) runs.push({ text: `${task.notes} ` });
  if (due) runs.push({ text: due });
  runs.push({ text: `\u2013 ${date}. ` });
  runs.push({ text: '\u2192 ', font: { bold: true } });
  runs.push({ text: statusLabel(task), font: { bold: true } });
  return {
    value: { richText: runs },
    plain: `\u25e6 ${task.title}${task.notes ? `: ${task.notes}` : ''}${due} \u2013 ${date}. \u2192 ${statusLabel(task)}`,
    indent: 1
  };
}

export async function buildWeeklyReport(payload: WeeklyPayload, outFile: string): Promise<void> {
  const start = parseIsoDate(payload.weekStart);
  const end = parseIsoDate(payload.weekEnd);
  const byDate = (a: Task, b: Task): number =>
    a.date.localeCompare(b.date) || (a.time ?? '').localeCompare(b.time ?? '');

  const weekTasks = payload.tasks
    .filter((t) => t.date >= payload.weekStart && t.date <= payload.weekEnd)
    .sort(byDate);
  const blocked = weekTasks.filter((t) => t.status === 'blocked');
  const recurring = weekTasks.filter((t) => t.recurrence !== 'none');
  const nextEndIso = isoDate(addDays(end, 7));
  const nextTasks = payload.tasks
    .filter((t) => t.date > payload.weekEnd && t.date <= nextEndIso)
    .sort(byDate);

  const lines: ReportLine[] = [];
  lines.push({
    value: '\u2610 INFORMATION SECURITY OPERATIONS.',
    bold: true,
    color: BLUE
  });
  lines.push({ spacer: true });
  lines.push({ value: '\u2726 Activities(This week)', bold: true });
  if (weekTasks.length) for (const task of weekTasks) lines.push(taskItem(task));
  else lines.push({ value: '\u25e6 No activities recorded this week.', indent: 1 });
  lines.push({ spacer: true });
  lines.push({ value: '\u2726 Challenges', bold: true });
  if (blocked.length) {
    for (const task of blocked) {
      lines.push({
        value: { richText: [{ text: `\u25e6 ${task.title}`, font: { bold: true } }] },
        plain: `\u25e6 ${task.title}`,
        indent: 1
      });
    }
  } else {
    lines.push({ value: 'No challenge faced', indent: 1 });
  }
  lines.push({ spacer: true });
  lines.push({ value: '\u2726 Activities(Next week)', bold: true });
  if (nextTasks.length) {
    for (const task of nextTasks) {
      lines.push({
        value: {
          richText: [
            { text: `\u25e6 ${task.title}`, font: { bold: true } },
            { text: ` \u2013 ${fmtLong(parseIsoDate(task.date))}.` }
          ]
        },
        plain: `\u25e6 ${task.title} \u2013 ${fmtLong(parseIsoDate(task.date))}.`,
        indent: 1
      });
    }
  } else if (recurring.length) {
    for (const task of recurring) {
      const repeats = task.recurrence === 'monthly' ? '(repeats monthly)' : '(repeats weekly)';
      lines.push({
        value: {
          richText: [
            { text: `\u25e6 ${task.title}`, font: { bold: true } },
            { text: ` ${repeats}` }
          ]
        },
        plain: `\u25e6 ${task.title} ${repeats}`,
        indent: 1
      });
    }
  } else {
    lines.push({ value: '\u25e6 No activities planned yet.', indent: 1 });
  }

  const workbook = newWorkbook();
  const ws = workbook.addWorksheet('Weekly Report');
  ws.columns = [{ width: 16 }, { width: 70 }, { width: 40 }, { width: 30 }];

  const lineBorder = {
    top: { style: 'thin' as const, color: { argb: 'FFBFBFBF' } },
    left: { style: 'thin' as const, color: { argb: 'FFBFBFBF' } },
    bottom: { style: 'thin' as const, color: { argb: 'FFBFBFBF' } },
    right: { style: 'thin' as const, color: { argb: 'FFBFBFBF' } }
  };

  // --- banner row -------------------------------------------------------
  ws.mergeCells('B1:C1');
  const banner = ws.getCell('A1');
  banner.value = `Week: ${fmtShort(start)} \u2013 ${fmtShort(end)} ${end.getFullYear()}`;
  banner.font = { ...WEEK_FONT, size: 12, bold: true, color: { argb: BLUE } };
  banner.alignment = { vertical: 'middle', horizontal: 'left' };
  const dept = ws.getCell('B1');
  dept.value = 'Information Security Department';
  dept.font = { ...WEEK_FONT, size: 13, bold: true };
  dept.alignment = { vertical: 'middle', horizontal: 'center' };
  const internal = ws.getCell('D1');
  internal.value = 'For Internal Use Only';
  internal.font = { ...WEEK_FONT, size: 11, color: { argb: RED } };
  internal.alignment = { vertical: 'middle', horizontal: 'right' };
  ws.getRow(1).height = 27;

  // --- header row -------------------------------------------------------
  ws.mergeCells('B2:D2');
  const labelHead = ws.getCell('A2');
  labelHead.value = 'Activity';
  labelHead.font = WEEK_FONT;
  labelHead.alignment = { vertical: 'middle', horizontal: 'center' };
  labelHead.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: GREY_FILL } };
  labelHead.border = lineBorder;
  const contentHead = ws.getCell('B2');
  contentHead.value = 'Activities';
  contentHead.font = WEEK_FONT;
  contentHead.alignment = { vertical: 'middle', horizontal: 'center' };
  contentHead.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: GREY_FILL } };
  for (let col = 2; col <= 4; col += 1) ws.getCell(2, col).border = lineBorder;
  ws.getRow(2).height = 21;

  // --- content rows -----------------------------------------------------
  const firstRow = 3;
  lines.forEach((line, index) => {
    const rowNo = firstRow + index;
    const row = ws.getRow(rowNo);

    if (line.spacer) {
      row.height = 7;
      for (let col = 1; col <= 4; col += 1) ws.getCell(rowNo, col).border = lineBorder;
      return;
    }

    ws.mergeCells(rowNo, 2, rowNo, 4);
    const cell = ws.getCell(rowNo, 2);
    cell.value = line.value ?? '';
    cell.font = {
      ...WEEK_FONT,
      bold: line.bold ?? false,
      ...(line.color ? { color: { argb: line.color } } : {})
    };
    cell.alignment = {
      vertical: 'top',
      horizontal: 'left',
      wrapText: true,
      indent: line.indent ?? 0
    };

    for (let col = 1; col <= 4; col += 1) ws.getCell(rowNo, col).border = lineBorder;

    const plain = line.plain ?? String(line.value ?? '');
    const linesHigh = Math.max(
      1,
      Math.ceil(plain.length / 118),
      ...plain.split('\n').map((part) => Math.ceil(part.length / 118))
    );
    row.height = Math.max(16, linesHigh * 14.5 + 4);
  });

  // --- left summary column ---------------------------------------------
  const lastRow = firstRow + lines.length - 1;
  ws.mergeCells(`A${firstRow}:A${lastRow}`);
  const summary = ws.getCell(`A${firstRow}`);
  summary.value = 'General Summary';
  summary.font = WEEK_FONT;
  summary.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
  summary.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: GREY_FILL } };

  polishSheet(ws, 2);
  await workbook.xlsx.writeFile(outFile);
}

