const DAY_WIDE = 128;

function dayTaskItem(task: Task): ReportLine {
  const base = taskItem(task);
  if (!task.time) return base;
  const prefix = `${task.time} · `;
  const v = base.value;
  const value =
    typeof v === 'object' && v !== null && 'richText' in v
      ? { richText: [{ text: prefix }, ...v.richText] }
      : base.value;
  return { ...base, value, plain: `${prefix}${base.plain ?? ''}` };
}

function logLineText(entry: DailyPayload['log'][number]): string {
  const time = new Date(entry.at).toLocaleTimeString(undefined, {
    hour: '2-digit',
    minute: '2-digit'
  });
  const title = `"${entry.taskTitle}"`;
  switch (entry.action) {
    case 'created':
      return `${time} — Created ${title}`;
    case 'status':
      return `${time} — Status: ${title} → ${
        entry.to ? STATUS_LABELS[entry.to as TaskStatus] ?? entry.to : entry.to ?? ''
      }`;
    case 'edited':
      return `${time} — Edited ${title}`;
    case 'moved':
      return `${time} — Moved ${title}: ${entry.from} → ${entry.to}`;
    case 'deleted':
      return `${time} — Deleted ${title}`;
    default:
      return `${time} — ${title}`;
  }
}

